-- Sweet Bites - estrutura inicial do banco (PostgreSQL)
-- Derivada do Diagrama de Classes revisado (situacao-1-documentacao).

CREATE TABLE usuario (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome               VARCHAR(120) NOT NULL,
    email              VARCHAR(160) NOT NULL,
    senha_hash         VARCHAR(100) NOT NULL,
    telefone           VARCHAR(20)  NOT NULL,
    papel              VARCHAR(20)  NOT NULL,
    tentativas_falhas  INTEGER      NOT NULL DEFAULT 0,
    bloqueado          BOOLEAN      NOT NULL DEFAULT FALSE,
    data_criacao       TIMESTAMP    NOT NULL,
    CONSTRAINT uk_usuario_email UNIQUE (email)
);

CREATE TABLE categoria (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(60)  NOT NULL,
    descricao  VARCHAR(255),
    CONSTRAINT uk_categoria_nome UNIQUE (nome)
);

CREATE TABLE imagem_produto (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo   VARCHAR(40) NOT NULL,
    dados  BYTEA       NOT NULL
);

CREATE TABLE cupcake (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(80)    NOT NULL,
    descricao     VARCHAR(1000)  NOT NULL,
    ingredientes  VARCHAR(500)   NOT NULL,
    preco         NUMERIC(10, 2) NOT NULL,
    estoque       INTEGER        NOT NULL,
    ativo         BOOLEAN        NOT NULL DEFAULT TRUE,
    categoria_id  BIGINT         NOT NULL REFERENCES categoria (id),
    imagem_id     BIGINT         REFERENCES imagem_produto (id),
    CONSTRAINT ck_cupcake_estoque CHECK (estoque >= 0),
    CONSTRAINT ck_cupcake_preco CHECK (preco > 0)
);
CREATE INDEX ix_cupcake_categoria ON cupcake (categoria_id);

CREATE TABLE pedido (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id        BIGINT         NOT NULL REFERENCES usuario (id),
    data_criacao      TIMESTAMP      NOT NULL,
    status            VARCHAR(30)    NOT NULL,
    subtotal          NUMERIC(10, 2) NOT NULL,
    frete             NUMERIC(10, 2) NOT NULL,
    valor_total       NUMERIC(10, 2) NOT NULL,
    forma_pagamento   VARCHAR(20)    NOT NULL
);
CREATE INDEX ix_pedido_usuario ON pedido (usuario_id);
CREATE INDEX ix_pedido_status_data ON pedido (status, data_criacao);

CREATE TABLE item_pedido (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id        BIGINT         NOT NULL REFERENCES pedido (id),
    cupcake_id       BIGINT         NOT NULL REFERENCES cupcake (id),
    quantidade       INTEGER        NOT NULL,
    preco_unitario   NUMERIC(10, 2) NOT NULL,
    CONSTRAINT ck_item_quantidade CHECK (quantidade BETWEEN 1 AND 20)
);
CREATE INDEX ix_item_pedido_pedido ON item_pedido (pedido_id);
CREATE INDEX ix_item_pedido_cupcake ON item_pedido (cupcake_id);

CREATE TABLE pagamento (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id       BIGINT         NOT NULL REFERENCES pedido (id),
    metodo          VARCHAR(20)    NOT NULL,
    status          VARCHAR(20)    NOT NULL,
    valor           NUMERIC(10, 2) NOT NULL,
    parcelas        INTEGER        NOT NULL DEFAULT 1,
    cartao_final    VARCHAR(4),
    pix_codigo      VARCHAR(255),
    pix_expira_em   TIMESTAMP,
    data_aprovacao  TIMESTAMP,
    CONSTRAINT uk_pagamento_pedido UNIQUE (pedido_id)
);
CREATE INDEX ix_pagamento_status_metodo ON pagamento (status, metodo);

CREATE TABLE entrega (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id          BIGINT       NOT NULL REFERENCES pedido (id),
    cep                VARCHAR(8)   NOT NULL,
    logradouro         VARCHAR(160) NOT NULL,
    numero             VARCHAR(10)  NOT NULL,
    complemento        VARCHAR(80),
    bairro             VARCHAR(80)  NOT NULL,
    cidade             VARCHAR(80)  NOT NULL,
    uf                 VARCHAR(2)   NOT NULL,
    tempo_estimado_min INTEGER      NOT NULL,
    data_prevista      TIMESTAMP    NOT NULL,
    CONSTRAINT uk_entrega_pedido UNIQUE (pedido_id)
);

CREATE TABLE notificacao (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id    BIGINT        NOT NULL REFERENCES usuario (id),
    pedido_id     BIGINT        REFERENCES pedido (id),
    mensagem      VARCHAR(255)  NOT NULL,
    lida          BOOLEAN       NOT NULL DEFAULT FALSE,
    data_criacao  TIMESTAMP     NOT NULL
);
CREATE INDEX ix_notificacao_usuario ON notificacao (usuario_id, lida);

CREATE TABLE token_recuperacao_senha (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT       NOT NULL REFERENCES usuario (id),
    token_hash  VARCHAR(64)  NOT NULL,
    expira_em   TIMESTAMP    NOT NULL,
    usado       BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT uk_token_hash UNIQUE (token_hash)
);
